// Builds the whole website for Hostinger into dist-hostinger/ and packs it as
// dist-hostinger.zip, ready to extract inside public_html.
//
//   /                 website pages (pre-built HTML, read by Google)
//   /app/             the auction app (not indexed)
//   /api/             PHP API for cloud sync (not indexed)
//   sitemap.xml, robots.txt, .htaccess, 404.html, favicon, assets/
//
// Run: npm run build:hostinger
import { execSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { SITE } from '../site/config.mjs';
import { allPages } from '../site/content.mjs';
import { renderPage } from '../site/layout.mjs';

const OUT = 'dist-hostinger';
const ZIP = 'dist-hostinger.zip';
const host = new URL(SITE.url).host;

const write = (path, text) => {
  const full = join(OUT, path);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, text);
};

// 1. The app, built for /app/ with the API at /api/.
rmSync(OUT, { recursive: true, force: true });
execSync('npx tsc --noEmit', { stdio: 'inherit' });
execSync('npx vite build --mode hostinger', { stdio: 'inherit' });
const appIndex = join(OUT, 'app', 'index.html');
writeFileSync(
  appIndex,
  readFileSync(appIndex, 'utf8').replace('<head>', '<head>\n    <meta name="robots" content="noindex, nofollow">'),
);

// 2. Website pages.
const css = readFileSync('site/site.css', 'utf8');
const cssVersion = createHash('sha1').update(css).digest('hex').slice(0, 8);
write('assets/site.css', css);
cpSync('site/assets', join(OUT, 'assets'), { recursive: true });
cpSync('public/favicon.svg', join(OUT, 'favicon.svg'));
// Google Search Console ownership file(s): must stay at the site root to keep the site verified.
for (const f of readdirSync('public').filter((f) => /^google[0-9a-f]+\.html$/.test(f))) cpSync(join('public', f), join(OUT, f));

const pages = allPages();
for (const page of pages) {
  const file = page.file ?? (page.path === '/' ? 'index.html' : page.path.replace(/^\//, '') + 'index.html');
  write(file, renderPage({ ...page, cssVersion }));
}

// 3. Sitemap: every public page, with language links between the home pages.
const today = new Date().toISOString().slice(0, 10);
const urls = pages
  .filter((p) => p.inSitemap !== false && !p.noindex)
  .map((p) => {
    const alt = p.alternates
      ? Object.entries(p.alternates)
          .map(([l, path]) => `\n    <xhtml:link rel="alternate" hreflang="${l}" href="${SITE.url}${path}"/>`)
          .join('') + `\n    <xhtml:link rel="alternate" hreflang="x-default" href="${SITE.url}/"/>`
      : '';
    return `  <url>\n    <loc>${SITE.url}${p.path}</loc>\n    <lastmod>${today}</lastmod>${alt}\n  </url>`;
  });
write(
  'sitemap.xml',
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${urls.join('\n')}\n</urlset>\n`,
);

// 4. robots.txt: the website is open; the app, its private auction links and the API are not.
write('robots.txt', `User-agent: *\nAllow: /\nDisallow: /app/\nDisallow: /api/\n\nSitemap: ${SITE.url}/sitemap.xml\n`);

// 5. .htaccess (Hostinger runs LiteSpeed, which reads it like Apache).
const altRules = SITE.altDomains
  .map((d) => `RewriteCond %{HTTP_HOST} ^(www\\.)?${d.replace(/\./g, '\\.')}$ [NC]\nRewriteRule ^ ${SITE.url}%{REQUEST_URI} [L,R=301]`)
  .join('\n');
write(
  '.htaccess',
  `# KhiladiAuction — generated by scripts/build-hostinger.mjs
Options -Indexes
DirectoryIndex index.html index.php
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
RewriteEngine On

# Other domains (e.g. the .in) -> main address, one permanent redirect
${altRules}

# Always https, and the address without www
RewriteCond %{HTTPS} !=on
RewriteCond %{HTTP:X-Forwarded-Proto} !https
RewriteRule ^ https://${host}%{REQUEST_URI} [L,R=301]
RewriteCond %{HTTP_HOST} ^www\\.${host.replace(/\./g, '\\.')}$ [NC]
RewriteRule ^ https://${host}%{REQUEST_URI} [L,R=301]

# The app: every /app/... address that isn't a real file opens the app
RewriteRule ^app$ /app/ [L,R=301]
RewriteCond %{REQUEST_FILENAME} !-f
RewriteRule ^app/ /app/index.html [L]
</IfModule>

<IfModule mod_headers.c>
Header always set X-Content-Type-Options "nosniff"
Header always set Referrer-Policy "strict-origin-when-cross-origin"
Header always set X-Frame-Options "SAMEORIGIN"
# Keep the app, private auction links and the API out of search results
<If "%{REQUEST_URI} =~ m#^/(app|api)/#">
  Header set X-Robots-Tag "noindex, nofollow"
</If>
# Built files have a fingerprint in their name, so they can be cached for a year
<If "%{REQUEST_URI} =~ m#^/app/assets/#">
  Header set Cache-Control "public, max-age=31536000, immutable"
</If>
<FilesMatch "\\.(html|xml|txt)$">
  Header set Cache-Control "no-cache"
</FilesMatch>
</IfModule>

<IfModule mod_expires.c>
ExpiresActive On
ExpiresByType text/css "access plus 30 days"
ExpiresByType image/png "access plus 30 days"
ExpiresByType image/svg+xml "access plus 30 days"
</IfModule>

<IfModule mod_deflate.c>
AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml application/javascript application/json application/xml image/svg+xml
</IfModule>
`,
);

// 6. The PHP API. config.php is never shipped: it holds the database password and is
//    created once on the server from config.sample.php, so a later upload can't overwrite it.
mkdirSync(join(OUT, 'api'), { recursive: true });
for (const f of readdirSync('server/api')) {
  if (f === 'config.php') continue;
  cpSync(join('server/api', f), join(OUT, 'api', f));
}
cpSync('server/schema.sql', join(OUT, 'api', 'schema.sql.txt'));
writeFileSync(join(OUT, 'api', '.htaccess'), readFileSync('server/api/.htaccess', 'utf8') + '<Files "schema.sql.txt">\n  Require all denied\n</Files>\n');

// 7. Pack it.
rmSync(ZIP, { force: true });
const tar = process.platform === 'win32' ? 'C:\\Windows\\System32\\tar.exe' : 'tar';
execSync(`"${tar}" -a -c -f ${ZIP} -C ${OUT} .`, { stdio: 'inherit' });

// 8. Report.
const missing = ['whatsapp', 'email', 'city'].filter((k) => !SITE[k]);
console.log(`\nBuilt ${pages.length} pages, the app and the API into ${OUT}/ and ${ZIP} (${Math.round(readFileSync(ZIP).length / 1024)} KB).`);
console.log(`Main address: ${SITE.url}`);
if (missing.length) console.warn(`\n⚠ Contact details not filled in site/config.mjs: ${missing.join(', ')}. Those lines are left out of the pages.`);
if (!existsSync('site/assets/og-image.png')) console.warn('⚠ site/assets/og-image.png is missing: share previews will have no picture.');
